"""章節裡「相關準則」區塊的定位（`1.<數字> 相關準則`，不只 1.4）。

為什麼只取這一段而不是整章：整章內文裡會順帶提到別的規範（施工方法描述、
相關章節交叉引用），抽起來是雜訊。「相關準則」是規範書自己宣告的依據清單。

小節號不寫死 1.4：實測（2026-10-07，真實規範書）有這一段的章裡，75 章編在 1.4，
4 章（01523、01574、02786、03110）編在 1.3。

實測本案規範書 86 章裡 79 章有此宣告、7 章沒有（01521、01630、01725、01820、02220、
02235、02900），共 1408 筆依據記錄。「依據記錄」是規則與字典兩層抽取器（LLM 關閉）對各章
區塊各抽一次的候選數合計，不是 `work_item_bases` 的列數（那個每個工項各存一份）。
79 章裡有 1 章（01523）的區塊抽不出任何候選，所以實際抽得到依據的是 78 章。
標準沒有資料來源可查證，只引述——這個判斷在 service 層依 `RegulationType` 做，不在這裡。
"""

import re

#: `1.<數字> 相關準則` 標題之後的內容，直到下一個 1.<數字> 小節、「2. 產品」、或文本結尾為止。
#: 小節號不限 1.4（實測 75 章編在 1.4、4 章編在 1.3）。
#: 使用 (?<!\S) 確保小節號在字邊界（不在數字或文字中間）。可能有多個相關準則區塊
#: （實測 7 章的標題出現不只一次）。
_BLOCK = re.compile(
    r"(?<!\S)1\.\d+\s*相關準則(.*?)(?=(?<!\S)1\.\d+\s|(?<!\S)2\.\s*產品|$)", re.S
)


def basis_block(chapter_text: str) -> str | None:
    """切出章節裡宣告依據的那一段。沒有這一段就回 None。

    可能有多個相關準則區塊（同一個小節號重複或不同小節號），
    此函數整合所有區塊。
    """
    blocks = []
    for match in _BLOCK.finditer(chapter_text):
        block = match.group(1).strip()
        if block:
            blocks.append(block)

    if not blocks:
        return None

    return " ".join(blocks)
